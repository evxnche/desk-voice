_glyphs = {}

def text(fb, s, x, y):
    """Draw `s` in black at (x, y) on FrameBuffer `fb`; returns the x after the last char."""
    for ch in s:
        o = ord(ch) - 32
        if 0 <= o < 95:
            g = _glyphs.get(o)
            if g is None:
                g = _glyphs[o] = framebuf.FrameBuffer(bytearray(DATA[o * 5:o * 5 + 5]), 5, 8, framebuf.MONO_VLSB)
            fb.blit(g, x, y, 0)
        x += 6
    return x
